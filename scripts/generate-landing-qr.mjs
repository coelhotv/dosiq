#!/usr/bin/env node
/**
 * generate-landing-qr.mjs
 *
 * Gera o SVG estático do QR code para https://dosiq.app/baixar?ct=qr.
 * Mantém o QR como arquivo estático em public/badges/qr-baixar.svg (RC3 E-1),
 * evitando qualquer import de biblioteca de QR no bundle do cliente.
 *
 * Uso:
 *   node scripts/generate-landing-qr.mjs          # regenera e grava o arquivo
 *   node scripts/generate-landing-qr.mjs --check  # verifica se está atualizado
 */

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import QRCode from 'qrcode'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(__dirname, '..')
const TARGET_FILE = path.resolve(ROOT, 'apps/web/public/badges/qr-baixar.svg')
const TARGET_URL = 'https://dosiq.app/baixar?ct=qr'

const COMMENT = '<!-- Generated by scripts/generate-landing-qr.mjs — DO NOT EDIT -->\n'

async function generateSvg() {
  const rawSvg = await QRCode.toString(TARGET_URL, {
    type: 'svg',
    margin: 1,
    errorCorrectionLevel: 'M',
    color: {
      dark: '#1b4332', // var(--lp-pine)
      light: '#ffffff',
    },
  })
  return `${COMMENT}${rawSvg.trim()}\n`
}

async function main() {
  const isCheck = process.argv.includes('--check')
  const expectedContent = await generateSvg()

  if (isCheck) {
    if (!fs.existsSync(TARGET_FILE)) {
      console.error(`[check-qr] Arquivo não encontrado: ${TARGET_FILE}`)
      process.exit(1)
    }
    const currentContent = fs.readFileSync(TARGET_FILE, 'utf-8')
    if (currentContent !== expectedContent) {
      console.error(`[check-qr] qr-baixar.svg difere do gerado pelo script. Execute: node scripts/generate-landing-qr.mjs`)
      process.exit(1)
    }
    console.log('[check-qr] qr-baixar.svg está atualizado e íntegro.')
    process.exit(0)
  }

  fs.mkdirSync(path.dirname(TARGET_FILE), { recursive: true })
  fs.writeFileSync(TARGET_FILE, expectedContent, 'utf-8')
  console.log(`[generate-qr] QR SVG gerado com sucesso em: ${path.relative(ROOT, TARGET_FILE)}`)
}

main().catch((err) => {
  console.error('[generate-qr] Erro:', err)
  process.exit(1)
})
